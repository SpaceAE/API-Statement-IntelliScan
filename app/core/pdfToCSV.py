_amount_clean = re.compile(r'[^0-9\.\-]+')


def _looks_tx_datetime(s: Optional[str]) -> bool:
	if not s:
		return False
	s = re.sub(r'\s+', ' ', str(s).strip())
	for pat in _DT_PATTERNS:
		if pat.match(s):
			return True
	if re.match(r'^\d{1,2}[/-]\d{1,2}[/-]\d{2,4}$', s):
		return True
	return False


def _is_tx_row(row: pd.Series) -> bool:
	dt = row.get('tx_datetime')
	desc = row.get('description_text') or ''
	chan = row.get('code_channel_raw') or ''
	joined = f'{(dt or "")} {(chan or "")} {(desc or "")}'.strip()

	if _HEADER_NOISE_RE.search(joined):
		return False
	if any(_is_disclaimer(str(v or '')) for v in (dt, desc, chan)):
		return False

	if not _looks_tx_datetime(str(dt) if dt is not None else None):
		return False

	if STRICT_AMOUNT_REQUIRED:
		has_amount = any(
			x is not None
			for x in (
				row.get('debit_amount'),
				row.get('credit_amount'),
				row.get('balance_amount'),
			)
		)
		return bool(has_amount)
	else:
		has_any = any(
			[
				any(
					x is not None
					for x in (
						row.get('debit_amount'),
						row.get('credit_amount'),
						row.get('balance_amount'),
					)
				),
				bool((chan or '').strip()),
				bool((desc or '').strip()),
			]
		)
		return has_any


def _to_float_or_none(x):
	if x is None:
		return None
	s = str(x).strip()
	if s == '' or s.lower() in {'-', 'na', 'none'}:
		return None

	# NEW: normalize เคสแยก token เป็นชิ้น ๆ
	# รวมช่องว่างรอบจุด/คอมม่า -> ให้เป็น "ติดกัน"
	s = re.sub(r'\s*\.\s*', '.', s)
	s = re.sub(r'\s*,\s*', ',', s)
	# วงเล็บติดเลข เช่น "( 100,000 )" -> "(100,000)"
	s = re.sub(r'\(\s*', '(', s)
	s = re.sub(r'\s*\)', ')', s)
	# เคสติดเครื่องหมายลบด้านท้าย เช่น "100,000-" -> "-100,000"
	if re.match(r'^\d[\d,]*-\s*$', s):
		s = '-' + s.rstrip('-').strip()

	neg = s.startswith('(') and s.endswith(')')
	s = s.replace('(', '').replace(')', '')
	s = s.replace('฿', '').replace(',', '').replace(' ', '')
	s = _amount_clean.sub('', s)  # เหลือเฉพาะ 0-9 . -

	if s in {'', '-', '.', '-.'}:
		return None
	try:
		v = float(s)
		return -v if neg else v
	except Exception:
		return None


