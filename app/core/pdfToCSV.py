def _detect_bank_brand(file_obj, password: Optional[str]) -> Optional[str]:
	"""
	อ่านข้อมูลหน้าแรกของไฟล์เพื่อระบุว่าเป็นสเตทเมนต์จากแบรนด์ใด
	คืนค่า: 'scb' หรือ None
	"""
	try:
		# ตรวจจับจาก pdfminer
		if _pdfminer_extract_text is not None:
			file_obj.seek(0)
			txt = _pdfminer_extract_text(file_obj) or ''
			norm = re.sub(r'\s+', ' ', txt).strip().lower()

			# คำสำคัญที่ใช้ในการตรวจจับ SCB
			scb_keywords = [
				'siam commercial bank',
				'scb call center',
				'ธนาคารไทยพาณิชย์',
				'scb easy',
				'statement with memo',
				'รายการเดินบัญชี พร้อมบันทึกช่วยจำ',
				'ธนาคารไทยพาณิชย์',
			]
			if any(keyword in norm for keyword in scb_keywords):
				file_obj.seek(0)
				return 'scb'
	except Exception as e:
		print(f'Error in pdfminer detection: {e}')
		pass

	# fallback ใช้ pdfplumber
	try:
		file_obj.seek(0)
		with pdfplumber.open(file_obj, password=password) as pdf:
			pages = pdf.pages[:2] if len(pdf.pages) >= 2 else pdf.pages
			buf = []
			for p in pages:
				t = p.extract_text() or ''
				buf.append(t)
			norm = re.sub(r'\s+', ' ', ' '.join(buf)).strip().lower()

			# คำสำคัญที่ใช้ในการตรวจจับ SCB
			scb_keywords = [
				'siam commercial bank',
				'scb call center',
				'ธนาคารไทยพาณิชย์',
				'scb easy',
				'statement with memo',
				'รายการเดินบัญชี พร้อมบันทึกช่วยจำ',
				'บันทึกช่วยจำ',
				'ธนาคาร',
				'เลขที่บัญชี',
				'ประเภทบัญชี',
				'ยอดคงเหลือ',
				'ถอน',
				'ฝาก',
				'debit',
				'credit',
				'บัญชี',
				'ธนาคารไทยพาณิชย์',
			]
			if any(keyword in norm for keyword in scb_keywords):
				file_obj.seek(0)
				return 'scb'
	except Exception as e:
		print(f'Error in pdfplumber detection: {e}')
		pass

	file_obj.seek(0)
	return None


# ---------- public API ----------
def extract_statement_df(
	file_obj, password: Optional[str] = None, return_meta: bool = False
) -> Union[pd.DataFrame, Tuple[pd.DataFrame, Dict]]:
	meta: Dict[str, Dict] = {'tables': {}, 'words': {}, 'fallback': {}}

	# -------- Brand gate --------
	brand = _detect_bank_brand(file_obj, password=password)
	if brand != 'scb':
		# ไม่ใช่ SCB หรือไม่รู้จักแบรนด์ -> ไม่รองรับ
		raise StatementFormatUnsupported(
			'This statement format is not supported. Please upload statements from SCB.'
		)

	# 1) tables-first
	file_obj.seek(0)
	frames = _extract_tables_with_pdfplumber(file_obj, password=password)
	meta['tables']['frames'] = len(frames)
	meta['tables']['rows_total'] = sum(len(f) for f in frames)
	if frames:
		out = pd.concat(
			[f for f in frames if isinstance(f, pd.DataFrame)], ignore_index=True
		)
		meta['tables']['rows_after_concat'] = len(out)
		if not out.empty:
			return (out, meta) if return_meta else out

	# 2) words-projection (robust + SCB hard bounds)
	file_obj.seek(0)
	df_words = _extract_by_words_projection(file_obj, password=password)
	meta['words']['rows'] = len(df_words)
	if not df_words.empty:
		return (df_words, meta) if return_meta else df_words

	# 3) text fallback (gaps + greedy)
	lines = _extract_lines_with_pdfminer_or_plumber(file_obj, password=password)
	meta['fallback']['lines'] = len(lines)
	df = _parse_text_rows_by_gaps(lines)
	meta['fallback']['rows'] = len(df)

	# ถึงจุดนี้ยังไม่มีข้อมูล แม้ตรวจพบว่าเป็น SCB -> แจ้ง parsing failed
	if df.empty:
		raise StatementParsingFailed(
			'ตรวจพบว่าเป็นสเตทเมนต์ SCB แต่ไม่พบธุรกรรมในไฟล์  '
			'โปรดตรวจสอบว่าเป็นไฟล์ที่สมบูรณ์, ไม่มีการสแกนเบี้ยว/เบลอ,'
			'มีหัวตาราง:'
			'วันที่/เวลา, รายการ/ช่องทาง, เดบิต, เครดิต, คงเหลือ, รายละเอียด/บันทึกช่วยจำ'
		)

	return (df, meta) if return_meta else df


def df_to_csv_bytes(df: pd.DataFrame) -> bytes:
	return df.to_csv(index=False).encode('utf-8')
