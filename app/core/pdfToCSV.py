# ---------- merge duplicate mapped columns ----------
_date_only_re = re.compile(r'^\d{1,2}[/-]\d{1,2}[/-]\d{2,4}$')
_time_only_re = re.compile(r'^\d{1,2}:\d{2}$')


def _drop_columns_safe(df: pd.DataFrame, cols_to_drop: List[str]) -> pd.DataFrame:
	safe = [
		c
		for c in dict.fromkeys(cols_to_drop)
		if isinstance(c, str) and c != '' and c in df.columns
	]
	if not safe:
		return df
	try:
		return df.drop(columns=safe, errors='ignore')
	except Exception as e:  # pragma: no cover - safety fallback
		logger.debug(f'_drop_columns_safe fallback: {e} | trying column selection')
		keep = [c for c in df.columns if c not in safe]
		return df.loc[:, keep]


def _merge_duplicate_mapped_cols(df: pd.DataFrame) -> pd.DataFrame:
	cols = list(df.columns)
	dup_groups: Dict[str, List[int]] = {}
	for i, c in enumerate(cols):
		dup_groups.setdefault(c, []).append(i)

	for col, idxs in dup_groups.items():
		if len(idxs) <= 1:
			continue
		base = cols[idxs[0]]
		for j in idxs[1:]:
			other = df.iloc[:, j]
			if col == 'tx_datetime':

				def _join_dt(a, b):
					a = (None if pd.isna(a) else str(a).strip()) or None
					b = (None if pd.isna(b) else str(b).strip()) or None
					if _date_only_re.match(a or '') and _time_only_re.match(b or ''):
						return f'{a} {b}'
					if _date_only_re.match(b or '') and _time_only_re.match(a or ''):
						return f'{b} {a}'
					return a or b

				df[base] = [_join_dt(x, y) for x, y in zip(df[base], other)]
			else:
				df[base] = df[base].combine_first(other)
		drop_cols = [cols[i] for i in idxs[1:]]
		df = _drop_columns_safe(df, drop_cols)
		cols = list(df.columns)
	return df


# ---------- money & code-channel helpers ----------
_MONEY_RE = re.compile(
	r"""
   (?<!\d:)                           # ด้านซ้ายห้ามเป็น "เลขตามด้วยโคลอน" (กัน 10:)
   (?:
       [()\-]?\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?   # มีคอมม่าเป็นหลักพัน เช่น 100,000.00
     | [()\-]?\d+\.\d{1,2}                        # มีทศนิยม เช่น 0.50, 25.00
     | [()\-]?\d{3,}                              # จำนวนเต็มตั้งแต่ 3 หลักขึ้นไป (กัน 00/10)
   )
   (?!:\d)                           # ด้านขวาห้ามเป็น ":เลข" (กัน :00)
   """,
	re.VERBOSE,
)


def _looks_money_token(t: str) -> bool:
	if not t:
		return False
	s = t.strip()
	if ':' in s:
		return False
	if _MONEY_RE.fullmatch(s):
		return True
	if re.fullmatch(r'\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?', s):
		return True
	if re.fullmatch(r'\d+\.\d{1,2}', s):
		return True
	if re.fullmatch(r'\d{2,}', s):
		return True
	return False


_CODE_PAT = re.compile(r'\b[0-9A-Za-z]+(?:/[0-9A-Za-z]+)+\b')


def _clean_code_channel(s: Optional[str]) -> Optional[str]:
	if not s:
		return s
	ss = re.sub(r'\s+', ' ', str(s)).strip()
	parts = [p for p in ss.split() if not _looks_money_token(p)]
	ss2 = ' '.join(parts).strip()
	m = _CODE_PAT.search(ss2)
	if m:
		return m.group(0).upper()
	parts2 = [p for p in parts if not re.fullmatch(r'\d+(?:\.\d+)?', p)]
	return ' '.join(parts2).strip() or None


# ---------- description normalizer ----------
_DESC_LABELS = [r'\bdesc\b', r'\bdescription\b', r'รายละเอียด']
_NOTE_LABELS = [r'\bnote\b', r'บันทึก', r'บันทึกช่วยจำ', r'บันทึกช่วยจํา']
_DESC_NOTE_HINT_RE = re.compile(
	r'\b(?:desc|description|รายละเอียด|note|บันทึก|บันทึกช่วยจำ|บันทึกช่วยจํา)\b',
	re.IGNORECASE,
)


def _normalize_desc_note(s: Optional[str]) -> Optional[str]:
	if not s:
		return s
	txt = re.sub(r'\s+', ' ', str(s)).strip()
	if _is_disclaimer(txt):
		return None

	desc = None
	note = None
	mdesc = re.search(
		r'('
		+ '|'.join(_DESC_LABELS)
		+ r')\s*:?\s*(.+?)(?=('
		+ '|'.join(_NOTE_LABELS)
		+ r')\s*:|\Z)',
		txt,
		re.IGNORECASE,
	)
	if mdesc:
		desc = mdesc.group(2).strip(' -,:;')

	mnote = re.search(
		r'(' + '|'.join(_NOTE_LABELS) + r')\s*:?\s*(.+)$', txt, re.IGNORECASE
	)
	if mnote:
		note = mnote.group(2).strip(' -,:;')

	if desc or note:
		return f'DESC : {desc or "-"}  NOTE : {note or "-"}'
	return txt or None


def _looks_desc_line(s: str) -> bool:
	s2 = re.sub(r'\s+', ' ', s or '').strip()
	if not s2:
		return False
	if _is_disclaimer(s2):
		return False
	return bool(_DESC_NOTE_HINT_RE.search(s2))


def _sanitize_description(s: Optional[str], code: Optional[str]) -> Optional[str]:
	if not s:
		return s
	norm = _normalize_desc_note(s)
	if norm and ('DESC :' in norm or 'NOTE :' in norm):
		return norm
	txt = re.sub(r'\s+', ' ', str(s)).strip()
	parts = [p for p in txt.split() if not _looks_money_token(p)]
	code_up = (code or '').strip().upper()
	parts = [p for p in parts if p.upper() != code_up and not _CODE_PAT.fullmatch(p)]
	cleaned = ' '.join(parts).strip(' -*,.;:')
	if not re.search(r'[A-Za-zก-ฮ]', cleaned):
		return None
	if _looks_desc_line(cleaned):
		return cleaned
	return cleaned or None


# ----- DESC/NOTE extractors (block-level) -----
_DESC_ANY = r'(?:desc|description|รายละเอียด)'
_NOTE_ANY = r'(?:note|บันทึก|บันทึกช่วยจำ|บันทึกช่วยจํา)'


def _block_to_text(lines_block: List[List[dict]]) -> str:
	parts = []
	for ln in lines_block:
		parts.append(' '.join((t.get('text') or '') for t in ln))
	txt = '\n'.join(parts)
	return re.sub(r'\s+', ' ', txt).strip()


def _extract_desc_note_from_text(txt: Optional[str]) -> Optional[str]:
	if not txt:
		return None
	s = re.sub(r'\s+', ' ', str(txt)).strip()
	mdesc = re.search(
		rf'{_DESC_ANY}\s*:?\s*(.+?)(?={_NOTE_ANY}\s*:|$)', s, re.IGNORECASE
	)
	mnote = re.search(rf'{_NOTE_ANY}\s*:?\s*(.+)$', s, re.IGNORECASE)
	desc = mdesc.group(1).strip(' -,:;') if mdesc else None
	note = mnote.group(1).strip(' -,:;') if mnote else None
	if desc or note:
		return f'DESC : {desc or "-"}  NOTE : {note or "-"}'
	return None


def _extract_desc_note_from_block(lines_block: List[List[dict]]) -> Optional[str]:
	raw = _block_to_text(lines_block)
	return _extract_desc_note_from_text(raw)


