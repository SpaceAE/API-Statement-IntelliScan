def _norm(s: str) -> str:
	s = (s or '').replace('\u200b', '').strip().lower()
	s = re.sub(r'\s+', ' ', s)
	return s


def _defkey(s: str) -> str:
	return re.sub(r'[^a-zA-Zก-ฮ0-9]+', '', _norm(s))


def _cell_norm(x):
	if x is None or (isinstance(x, float) and pd.isna(x)):
		return None
	s = str(x).replace('\u200b', '').replace('\xa0', ' ')
	s = re.sub(r'\s+', ' ', s).strip()
	return s


