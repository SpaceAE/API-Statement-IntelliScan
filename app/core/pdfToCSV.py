def _extract_lines_with_pdfminer_or_plumber(
	file_obj, password: Optional[str]
) -> List[str]:
	lines: List[str] = []
	if _pdfminer_extract_text is not None:
		try:
			file_obj.seek(0)
			txt = _pdfminer_extract_text(file_obj) or ''
			tmp = [ln.strip() for ln in txt.splitlines() if ln.strip()]
			if tmp:
				lines = tmp
				file_obj.seek(0)
				return lines
		except Exception:
			pass

	file_obj.seek(0)
	with pdfplumber.open(file_obj, password=password) as pdf:
		for p in pdf.pages:
			text = p.extract_text() or ''
			for ln in text.splitlines():
				ln = ln.strip()
				if ln:
					lines.append(ln)
	file_obj.seek(0)
	return lines


def _parse_text_rows_by_gaps(lines: List[str]) -> pd.DataFrame:
	rows: List[Dict] = []
	pending: Optional[Dict] = None
	date_pat = re.compile(r'\b\d{1,2}/\d{1,2}/\d{2,4}\b')
	time_pat = re.compile(r'\b\d{1,2}:\d{2}\b')

	for ln in lines:
		if not ln:
			continue
		if _is_disclaimer(ln):
			continue

		if date_pat.search(ln):
			if pending:
				# สรุป DESC/NOTE ของ pending ก่อนหน้า
				if pending.get('description_text'):
					dn = _extract_desc_note_from_text(pending['description_text'])
					if dn:
						pending['description_text'] = dn
				rows.append(pending)
			pending = {
				'tx_datetime': None,
				'code_channel_raw': None,
				'debit_amount': None,
				'credit_amount': None,
				'balance_amount': None,
				'description_text': None,
			}
			dt = ln.strip()
			if time_pat.search(dt) and '/' in dt:
				mdt = re.search(r'\d{1,2}/\d{1,2}/\d{2,4}\s+\d{1,2}:\d{2}', dt)
				pending['tx_datetime'] = mdt.group(0) if mdt else dt
			else:
				date_only = re.search(r'\d{1,2}/\d{1,2}/\d{2,4}', dt).group(0)
				pending['tx_datetime'] = date_only
			continue

		if pending:
			if pending.get('tx_datetime') and (
				time_pat.search(ln) and ':' in ln and '/' not in ln
			):
				pending['tx_datetime'] = (
					f'{pending["tx_datetime"]} {time_pat.search(ln).group(0)}'
				)
				continue

			if any(
				k in _norm(ln)
				for k in [
					'x1',
					'x2',
					'enet',
					'pos',
					'sipi',
					'atm',
					'trf',
					'kb',
					'ktb',
					'scb',
				]
			):
				if not _is_disclaimer(ln):
					pending['code_channel_raw'] = (
						(pending.get('code_channel_raw') or '')
						+ (' ' if pending.get('code_channel_raw') else '')
						+ ln
					)

			raw_money_matches = [m for m in _MONEY_RE.finditer(ln)]

			def _not_time_fragment(m):
				start, end = m.span()
				left = ln[max(0, start - 2) : start]
				right = ln[end : min(len(ln), end + 2)]
				# กันรูปแบบ d:dd ทั้งซ้ายและขวา
				return not (re.match(r'\d:$', left) or re.match(r'^:\d', right))

			money = [m.group(0) for m in raw_money_matches if _not_time_fragment(m)]

			if money:
				for field in ('debit_amount', 'credit_amount', 'balance_amount'):
					if pending.get(field) is None and money:
						pending[field] = money.pop(0)
					if not money:
						break

			if not _is_disclaimer(ln):
				if pending.get('description_text'):
					pending['description_text'] = (
						pending['description_text'] + ' ' + ln
					).strip()
				else:
					pending['description_text'] = ln

	if pending:
		if pending.get('description_text'):
			dn = _extract_desc_note_from_text(pending['description_text'])
			if dn:
				pending['description_text'] = dn
		rows.append(pending)

	if not rows:
		return pd.DataFrame(columns=TARGET_COLS)
	df = pd.DataFrame(rows, columns=TARGET_COLS)
	return _standardize_df(df)


