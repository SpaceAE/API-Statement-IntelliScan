SCB_RELATIVE_BOUNDS = [
	('tx_datetime', 0.00, 0.17),
	('code_channel_raw', 0.17, 0.36),
	('debit_amount', 0.36, 0.48),
	('credit_amount', 0.48, 0.60),
	('balance_amount', 0.60, 0.74),
	('description_text', 0.74, 1.00),
]


def _categorize_header_token(txt: str) -> Optional[str]:
	t = _norm(txt)
	for key, variants in HEADER_KEYS:
		for v in variants:
			if _norm(v) in t:
				return key
	return None


def _infer_header_bounds_from_top(page) -> List[Tuple[str, float, float]]:
	words = page.extract_words(extra_attrs=['x0', 'x1', 'top', 'bottom']) or []
	if not words:
		return []
	H = page.height
	top_words = [w for w in words if w['top'] < H * 0.40]
	buckets: Dict[str, List[float]] = {}
	for w in top_words:
		key = _categorize_header_token(w['text'])
		if key:
			mid = (w['x0'] + w['x1']) / 2.0
			buckets.setdefault(key, []).append(mid)
	if len(buckets) < 3:
		return []
	centers = {k: sum(v) / len(v) for k, v in buckets.items()}
	ordered = sorted(centers.items(), key=lambda kv: kv[1])
	bounds: List[Tuple[str, float, float]] = []
	for i, (k, mid) in enumerate(ordered):
		left_mid = ordered[i - 1][1] if i > 0 else 0.0
		right_mid = ordered[i + 1][1] if i + 1 < len(ordered) else page.width
		x0 = (left_mid + mid) / 2 if i > 0 else 0.0
		x1 = (mid + right_mid) / 2 if i + 1 < len(ordered) else page.width
		bounds.append((k, x0, x1))
	return bounds


def _get_desc_x0(bounds: List[Tuple[str, float, float]], page_width: float) -> float:
	"""
	คืนค่า x0 ของคอลัมน์ description_text ถ้ามีใน bounds
	ถ้าไม่มี ให้ fallback เป็นสัดส่วนคงที่ (เช่น 0.74 ของความกว้างหน้า)
	"""
	for k, x0, x1 in bounds:
		if k == 'description_text':
			return float(x0)
	return page_width * 0.74  # fallback ตาม SCB_RELATIVE_BOUNDS


def _collect_desc_block_text(page, y0: float, y1: float, desc_x0: float) -> str:
	"""
	เก็บคำทั้งหมดในกรอบ (x >= desc_x0) และ y อยู่ระหว่าง [y0, y1]
	เรียงตาม y จากบนลงล่าง แล้วต่อเป็นข้อความบรรทัดเดียว (คั่นด้วยเว้นวรรค)
	หมายเหตุ: ใช้ extract_words เพื่อให้แม่นยำกว่า extract_text ในเคสคอลัมน์
	"""
	words = page.extract_words(extra_attrs=['x0', 'x1', 'top', 'bottom', 'text']) or []
	y_tol = 1.0
	lines: list[list[dict]] = []
	curr: list[dict] = []

	# เลือกเฉพาะคำที่อยู่ในโซน Description/Note
	tokens = [
		w
		for w in words
		if (
			(w['x0'] >= desc_x0 - 1)
			and (w['top'] >= y0 - y_tol)
			and (w['bottom'] <= y1 + y_tol)
		)
	]
	tokens.sort(key=lambda d: (d['top'], d['x0']))

	for w in tokens:
		if not curr or abs(curr[0]['top'] - w['top']) <= 4.5:
			curr.append(w)
		else:
			lines.append(curr)
			curr = [w]
	if curr:
		lines.append(curr)

	# ต่อ token เป็น text ต่อบรรทัด แล้วรวมทั้งบล็อก
	parts: list[str] = []
	for ln in lines:
		txt = ' '.join(t['text'] for t in ln if t.get('text')).strip()
		if txt:
			parts.append(txt)
	return ' '.join(parts).strip()


def _assign_cells_from_tokens(
	tokens: List[dict], bounds: List[Tuple[str, float, float]]
) -> Dict[str, str]:
	cells: Dict[str, str] = {k: '' for k, *_ in bounds}
	for tok in tokens:
		mid = (tok['x0'] + tok['x1']) / 2.0
		for k, x0, x1 in bounds:
			if x0 - 1 <= mid <= x1 + 1:
				text = (tok['text'] or '').strip()
				if k == 'code_channel_raw' and _looks_money_token(text):
					break
				if _is_disclaimer(text):
					break
				cells[k] = (cells[k] + ' ' + text).strip()
				break
	return cells


def _extract_by_words_projection(file_obj, password: Optional[str]) -> pd.DataFrame:
	rows_all: List[Dict] = []
	with pdfplumber.open(file_obj, password=password) as pdf:
		for page in pdf.pages:
			bounds = _infer_header_bounds_from_top(page)
			if not bounds:
				W = page.width
				bounds = [(k, W * a, W * b) for (k, a, b) in SCB_RELATIVE_BOUNDS]

			# x เริ่มของโซน Description/Note
			desc_x0 = _get_desc_x0(bounds, page.width)

			words = (
				page.extract_words(extra_attrs=['x0', 'x1', 'top', 'bottom', 'text'])
				or []
			)
			if not words:
				continue

			start_y = (
				min(
					[
						w['top']
						for w in words
						if re.search(r'\b\d{1,2}/\d{1,2}/\d{2,4}\b', w['text'])
					],
					default=page.height * 0.25,
				)
				- 4
			)

			y_tol = 4.5
			lines: List[List[dict]] = []
			for w in sorted(
				(t for t in words if t['top'] >= start_y),
				key=lambda d: (d['top'], d['x0']),
			):
				if not lines or abs(lines[-1][0]['top'] - w['top']) > y_tol:
					lines.append([w])
				else:
					lines[-1].append(w)

			i = 0
			while i < len(lines):
				line_tokens = lines[i]
				line_text = ' '.join(t['text'] for t in line_tokens).strip()
				if _HEADER_NOISE_RE.search(line_text.lower()) or _is_disclaimer(
					line_text
				):
					i += 1
					continue

				has_date_hint = bool(
					re.search(r'\b\d{1,2}/\d{1,2}/\d{2,4}\b', line_text)
					or re.search(r'\b\d{4}-\d{2}-\d{2}\b', line_text)
				)
				if not has_date_hint:
					i += 1
					continue

				base = _assign_cells_from_tokens(line_tokens, bounds)

				# ต่อบรรทัดถัด ๆ ไป
				j = i + 1
				while j < len(lines):
					nxt_tokens = lines[j]
					nxt_text = ' '.join(t['text'] for t in nxt_tokens).strip()
					if _is_disclaimer(nxt_text):
						j += 1
						continue
					if re.search(r'\b\d{1,2}/\d{1,2}/\d{2,4}\b', nxt_text) or re.search(
						r'\b\d{4}-\d{2}-\d{2}\b', nxt_text
					):
						break

					nxt_cells = _assign_cells_from_tokens(nxt_tokens, bounds)

					if base.get('tx_datetime') and _time_only_re.match(
						(nxt_cells.get('tx_datetime') or '').strip()
					):
						base['tx_datetime'] = (
							base['tx_datetime'] + ' ' + nxt_cells['tx_datetime']
						).strip()

					columns_to_fill = [
						'code_channel_raw',
						'debit_amount',
						'credit_amount',
						'balance_amount',
					]
					for k in columns_to_fill:
						if (not base.get(k)) and nxt_cells.get(k):
							base[k] = nxt_cells[k]

					dtxt = nxt_cells.get('description_text', '')
					if dtxt and not _is_disclaimer(dtxt):
						base['description_text'] = (
							base.get('description_text', '')
							+ ('\\n' if base.get('description_text') else '')
							+ dtxt
						).strip()
					elif _looks_desc_line(nxt_text):
						base['description_text'] = (
							base.get('description_text', '')
							+ ('\\n' if base.get('description_text') else '')
							+ nxt_text
						).strip()
					j += 1

				# ถ้ายังไม่มี description_text ให้ดูจากโซนขวาหลังเส้นแบ่ง (desc_x0)
				if not (base.get('description_text') or '').strip():
					y0 = lines[i][0]['top'] - 2
					y1 = lines[(j - 1 if j > i else i)][0]['bottom'] + 2
					raw_right = _collect_desc_block_text(page, y0, y1, desc_x0)
					blk_desc = _extract_desc_note_from_text(raw_right)
					if blk_desc and not _is_disclaimer(blk_desc):
						base['description_text'] = blk_desc

				# ทำความสะอาดก่อนบันทึก
				cc = _clean_code_channel(base.get('code_channel_raw'))
				desc = _sanitize_description(base.get('description_text'), cc)
				base['code_channel_raw'] = cc
				base['description_text'] = desc

				rows_all.append(
					{
						'tx_datetime': base.get('tx_datetime') or None,
						'code_channel_raw': base.get('code_channel_raw') or None,
						'debit_amount': base.get('debit_amount') or None,
						'credit_amount': base.get('credit_amount') or None,
						'balance_amount': base.get('balance_amount') or None,
						'description_text': base.get('description_text') or None,
					}
				)
				i = j

	if not rows_all:
		return pd.DataFrame(columns=TARGET_COLS)
	df = pd.DataFrame(rows_all, columns=TARGET_COLS)
	_log_df(df, 'words-projection raw')
	return _standardize_df(df)


